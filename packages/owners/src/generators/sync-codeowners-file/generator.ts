import {
  createProjectGraphAsync,
  formatFiles,
  type NxJsonConfiguration,
  ProjectGraph,
  readNxJson,
  Tree,
} from '@nx/devkit';
import {
  findMatchingProjects,
  type SyncGeneratorResult,
} from '@nx/devkit/internal';
import {
  exitWithError,
  OwnerId,
  OwnershipPattern,
  ProjectOwnersConfig,
  validateAndSetDefaultsForRootConfig,
} from '../../config';

type ProjectOwnersConfigMap = Map<
  string,
  {
    owners: string[];
    description?: string;
    scopedFileOverrides?: Record<
      string,
      { owners: string[]; description?: string }
    >;
  }
>;

export async function syncCodeownersFileGenerator(
  tree: Tree
): Promise<SyncGeneratorResult> {
  const nxJson: NxJsonConfiguration = readNxJson(tree) ?? {};
  let rootOwners = nxJson.owners;
  // Owners is not enabled at all in nx.json, do nothing
  if (!rootOwners) {
    return;
  }

  // `true` shorthand to enable the feature but delegate to project.json
  if (typeof rootOwners === 'boolean') {
    rootOwners = {};
  }

  // Ensure the config is valid before proceeding
  if (!validateAndSetDefaultsForRootConfig(rootOwners)) {
    // this return won't be reached, but it lets TS know that rootOwners is a valid RootOwnersConfig outside of this block
    return;
  }

  const projectGraph = await createProjectGraphAsync();
  const projectOwnersConfig: ProjectOwnersConfigMap = new Map();

  let codeowners =
    createComment([
      '------------------------------------------------------------------------------------------------------------',
      'DO NOT EDIT - This file was generated by @nx/owners, update your Nx owners config and run `nx sync`',
      '------------------------------------------------------------------------------------------------------------',
    ]) + '\n';

  // Extract any patterns which have been explicitly marked as having no owners and applied them later
  const patternsWithOwners: Array<OwnershipPattern> = [];
  const patternsWithoutOwners: Array<OwnershipPattern> = [];
  for (const pattern of rootOwners.patterns) {
    if (pattern.owners === false) {
      patternsWithoutOwners.push(pattern);
    } else {
      patternsWithOwners.push(pattern);
    }
  }

  codeowners += generateContentForPatterns(
    patternsWithOwners, // only apply the patterns with owners upfront
    projectGraph,
    projectOwnersConfig,
    rootOwners.prefix
  );

  for (const [projectName, projectConfig] of Object.entries(
    projectGraph.nodes
  )) {
    const matchingProjectOwnersConfig = projectOwnersConfig.get(projectName);
    const ownersFromRootConfig = matchingProjectOwnersConfig?.owners ?? [];
    const ownersFromProjectConfig: ProjectOwnersConfig =
      (projectConfig.data as any).owners ?? {};

    if (
      ownersFromRootConfig.length === 0 &&
      Object.keys(ownersFromProjectConfig).length === 0
    ) {
      // No owners config for project
      continue;
    }

    /**
     * Compare owners from root config and project config and apply minimal config necessary (e.g. the project level config
     * could override for specific paths, the root always applies to all paths from that project root).
     *
     * NOTE: The path needs to start with / in order to specify that path. If the path does not start with /, it will match
     * any subpath within the workspace that starts with that path.
     *
     * E.g. /apps/ means the apps directory at the root of the workspace, apps/ means any apps directory at any level.
     *
     * Reference: https://docs.github.com/en/repositories/managing-your-repositorys-settings-and-features/customizing-your-repository/about-code-owners
     */
    const projectRootWithLeadingSlash = `/${projectConfig.data.root}`;

    // If there is `**/*` or `*` in the project config, it means that the root config should not be applied to this project
    const ownerIdsForProjectRoot =
      Object.keys(ownersFromProjectConfig).includes('**/*') ||
      Object.keys(ownersFromProjectConfig).includes('*')
        ? (ownersFromProjectConfig['**/*'] ?? ownersFromProjectConfig['*'])
        : ownersFromRootConfig;

    const ownerIdsForProjectRootArr = Array.isArray(ownerIdsForProjectRoot)
      ? ownerIdsForProjectRoot
      : ownerIdsForProjectRoot.owners;

    // Multiple patterns can match the same project (e.g. a `["*"]` catch-all plus a
    // more specific pattern), so dedupe owners while preserving first-seen order.
    const dedupedOwnerIdsForProjectRoot = Array.from(
      new Set(ownerIdsForProjectRootArr)
    );

    // Project root
    if (dedupedOwnerIdsForProjectRoot.length > 0) {
      codeowners += createCodeownersEntry(
        `${projectRootWithLeadingSlash}/`,
        dedupedOwnerIdsForProjectRoot,
        matchingProjectOwnersConfig?.description?.split('\n')
      );
    }

    // Merge scoped file overrides from root config with project-level overrides
    // Project.json entries take precedence for duplicate file patterns
    const mergedFileOverrides: Record<
      string,
      { owners: OwnerId[]; description?: string }
    > = { ...matchingProjectOwnersConfig?.scopedFileOverrides };

    // Project-level overrides win for duplicate file patterns
    for (const [pathOverride, config] of Object.entries(
      ownersFromProjectConfig
    )) {
      if (pathOverride === '**/*' || pathOverride === '*') {
        continue;
      }
      const owners: OwnerId[] = Array.isArray(config) ? config : config.owners;
      const description = Array.isArray(config)
        ? undefined
        : config.description;
      mergedFileOverrides[pathOverride] = { owners, description };
    }

    for (const [pathOverride, { owners, description }] of Object.entries(
      mergedFileOverrides
    )) {
      codeowners += createCodeownersEntry(
        `${projectRootWithLeadingSlash}/${pathOverride}`,
        owners,
        description?.split('\n')
      );
    }
    codeowners += '\n';
  }

  if (rootOwners.format === 'gitlab' && rootOwners.sections) {
    for (const section of rootOwners.sections) {
      let sectionHeader = `[${section.name}]`;
      if (section.optional) {
        sectionHeader = `^${sectionHeader}`;
      }
      if (section.numberOfRequiredApprovals) {
        sectionHeader += `[${section.numberOfRequiredApprovals}]`;
      }
      if (section.defaultOwners) {
        sectionHeader += ` ${section.defaultOwners.join(' ')}`;
      }

      codeowners += `${sectionHeader}\n`;

      // we create a local projectOwnersConfig for the section to avoid polluting the global one
      const innerProjectOwnersConfig: ProjectOwnersConfigMap = new Map();
      codeowners += generateContentForPatterns(
        section.patterns,
        projectGraph,
        innerProjectOwnersConfig,
        rootOwners.prefix
      );
      if (innerProjectOwnersConfig.size > 0) {
        for (const project of innerProjectOwnersConfig.keys()) {
          const projectConfig = innerProjectOwnersConfig.get(project);
          if (projectConfig) {
            codeowners += createCodeownersEntry(
              `/${projectGraph.nodes[project].data.root}/`,
              projectConfig.owners,
              projectConfig.description?.split('\n')
            );
          }
        }
        codeowners += '\n';
      }
    }
  }

  codeowners += generateContentForPatterns(
    patternsWithoutOwners, // apply the patterns which explicitly have no owners last
    projectGraph,
    projectOwnersConfig,
    rootOwners.prefix
  );

  // Ensure the file only ends with a single newline
  codeowners = codeowners.trimEnd() + '\n';

  tree.write(rootOwners.outputPath, codeowners);

  await formatFiles(tree);

  return {
    outOfSyncMessage: `${rootOwners.outputPath} does not match the Nx owners configuration.`,
  };
}

export default syncCodeownersFileGenerator;

function createComment(lines: string[]): string {
  return `# ${lines.join('\n# ')}\n`;
}

function createCodeownersEntry(
  pattern: string,
  owners: OwnerId[] | false,
  commentLines?: string[]
): string {
  return `${
    commentLines?.length ? createComment(commentLines) : ''
  }${pattern}${owners && owners.length ? ` ${owners.join(' ')}` : ''}\n`;
}

function generateContentForPatterns(
  patterns: Array<OwnershipPattern>,
  projectGraph: ProjectGraph,
  projectOwnersConfig: ProjectOwnersConfigMap,
  ownersPrefix?: string
): string {
  let content = '';

  for (const config of patterns) {
    // Pattern with both projects and files: scope file patterns to matched project roots
    if ('files' in config && 'projects' in config) {
      if (
        !Array.isArray(config.projects) ||
        config.projects.length === 0 ||
        !Array.isArray(config.files) ||
        config.files.length === 0
      ) {
        continue;
      }

      const matchingProjects = findMatchingProjects(
        config.projects,
        projectGraph.nodes
      );
      const effectivePrefix = config.prefix ?? ownersPrefix;
      const ownersWithPrefix: OwnerId[] | false = Array.isArray(config.owners)
        ? applyPrefixIfNeeded(
            config.owners,
            effectivePrefix,
            config.applyPrefix
          )
        : config.owners;

      for (const project of matchingProjects) {
        if (!projectOwnersConfig.has(project)) {
          projectOwnersConfig.set(project, {
            owners: [],
          });
        }
        const projectConfig = projectOwnersConfig.get(project)!;
        if (!projectConfig.scopedFileOverrides) {
          projectConfig.scopedFileOverrides = {};
        }

        if (Array.isArray(ownersWithPrefix)) {
          for (const filePattern of config.files) {
            // Only set if not already claimed by a previous pattern (first writer wins for scoped overrides from root config)
            if (!projectConfig.scopedFileOverrides[filePattern]) {
              projectConfig.scopedFileOverrides[filePattern] = {
                owners: ownersWithPrefix,
                description: config.description,
              };
            }
          }
        }
      }
      continue;
    }

    if ('files' in config) {
      const { files, owners } = config;
      if (!files || files.length === 0) {
        continue;
      }
      const effectivePrefix = config.prefix ?? ownersPrefix;
      const ownersWithPrefix: OwnerId[] | false = Array.isArray(owners)
        ? applyPrefixIfNeeded(owners, effectivePrefix, config.applyPrefix)
        : owners;
      for (const filePattern of files) {
        content += createCodeownersEntry(
          filePattern,
          ownersWithPrefix,
          config.description?.split('\n')
        );
      }
      content += '\n';
      continue;
    }

    if (!Array.isArray(config.projects) || config.projects.length === 0) {
      continue;
    }

    const matchingProjects = findMatchingProjects(
      config.projects,
      projectGraph.nodes
    );
    for (const project of matchingProjects) {
      if (!projectOwnersConfig.has(project)) {
        projectOwnersConfig.set(project, {
          owners: [],
          description: config.description,
        });
      }
      const projectConfig = projectOwnersConfig.get(project);
      if (projectConfig) {
        if (Array.isArray(config.owners)) {
          const effectivePrefix = config.prefix ?? ownersPrefix;
          projectConfig.owners.push(
            ...applyPrefixIfNeeded(
              config.owners,
              effectivePrefix,
              config.applyPrefix
            )
          );
        }
        // Merge multiple unique descriptions for the same project (separated by newline)
        if (projectConfig.description !== config.description) {
          projectConfig.description = projectConfig.description
            ? projectConfig.description + `\n` + config.description
            : config.description;
        }
      }
    }
  }

  return content;
}

function applyPrefixIfNeeded(
  owners: OwnerId[],
  ownersPrefix?: string,
  applyPrefixFlag?: boolean
): OwnerId[] {
  if (!ownersPrefix) {
    return owners;
  }
  if (applyPrefixFlag === false) {
    return owners;
  }
  const normalizedPrefix = ownersPrefix.endsWith('/')
    ? ownersPrefix.slice(0, -1)
    : ownersPrefix;
  return owners.map((o) => `${normalizedPrefix}/${o}`);
}
