import { logger } from '@nx/devkit';

// Helper behavior was removed in v24; exports remain only as inert stubs.
// Keep their imports loadable while existing Vite configs are migrated.
export const NX_VITE_TS_PATHS_DEPRECATION_MESSAGE =
  'The `nxViteTsPaths` plugin from `@nx/vite/plugins/nx-tsconfig-paths.plugin` was removed in Nx v24. The remaining export is an inert compatibility stub and does not configure builds. Use native `resolve.tsconfigPaths` when supported by the installed Vite version, or a compatible `vite-tsconfig-paths` plugin. Follow the config-helper migration instructions generated by `nx migrate`.';

export const NX_COPY_ASSETS_PLUGIN_DEPRECATION_MESSAGE =
  'The `nxCopyAssetsPlugin` plugin from `@nx/vite/plugins/nx-copy-assets.plugin` was removed in Nx v24. The remaining export is an inert compatibility stub and does not configure builds. Preserve asset paths and watch behavior using native `publicDir`, a compatible `vite-plugin-static-copy`, or local configuration. Follow the config-helper migration instructions generated by `nx migrate`.';

let nxViteTsPathsWarned = false;
let nxCopyAssetsPluginWarned = false;

// Warn-once per process so users don't see the message repeated on every
// dev-server HMR reload or vitest run within the same Node process.
export function warnNxViteTsPathsDeprecation(): void {
  if (nxViteTsPathsWarned) return;
  nxViteTsPathsWarned = true;
  logger.warn(NX_VITE_TS_PATHS_DEPRECATION_MESSAGE);
}

export function warnNxCopyAssetsPluginDeprecation(): void {
  if (nxCopyAssetsPluginWarned) return;
  nxCopyAssetsPluginWarned = true;
  logger.warn(NX_COPY_ASSETS_PLUGIN_DEPRECATION_MESSAGE);
}
