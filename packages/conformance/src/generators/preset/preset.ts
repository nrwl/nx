import {
  ensurePackage,
  formatFiles,
  GeneratorCallback,
  NX_VERSION,
  readProjectConfiguration,
  runTasksInSerial,
  Tree,
  updateJson,
  updateProjectConfiguration,
} from '@nx/devkit';
import createRuleGenerator from '../create-rule/create-rule';

export default async function preset(tree: Tree): Promise<GeneratorCallback> {
  const tasks: GeneratorCallback[] = [];

  // Ensure nx.json exists
  if (!tree.exists('nx.json')) {
    tree.write('nx.json', '{}');
  }

  // Ensure package manager workspaces are used
  updateJson(tree, 'package.json', (json) => {
    json.workspaces = json.workspaces || [];
    if (!json.workspaces.includes('packages/*')) {
      json.workspaces.push('packages/*');
    }
    return json;
  });

  // Install the @nx/js package
  ensurePackage('@nx/js', NX_VERSION);

  const { initGenerator, libraryGenerator, setupPrettierGenerator } =
    await import('@nx/js');

  const initTask = await initGenerator(tree, {
    addTsPlugin: true,
  });
  tasks.push(initTask);

  const libraryTask = await libraryGenerator(tree, {
    name: 'conformance-rules',
    directory: 'packages/conformance-rules',
    config: 'npm-scripts',
    useProjectJson: false,
  });
  tasks.push(libraryTask);

  // Clean up the extra TS plugin config
  // TODO: discuss with CLI team
  updateJson(tree, 'nx.json', (json) => {
    json.plugins = json.plugins.filter((plugin) => {
      if (plugin.plugin !== '@nx/js/typescript') {
        return true;
      }
      if (Array.isArray(plugin.exclude)) {
        return false;
      }
      if (Array.isArray(plugin.include)) {
        delete plugin.include;
      }
      return true;
    });

    return json;
  });

  // Remove placeholder npm scripts
  // TODO: discuss with CLI team
  if (tree.exists('packages/conformance-rules/package.json')) {
    updateJson(tree, 'packages/conformance-rules/package.json', (json) => {
      json.scripts = {};
      return json;
    });
  }

  // Ensure apps and libs directories do not exist
  // TODO: discuss with CLI team
  if (tree.exists('apps')) {
    tree.delete('apps');
  }
  if (tree.exists('libs')) {
    tree.delete('libs');
  }

  const prettierTask = await setupPrettierGenerator(tree, {});
  tasks.push(prettierTask);

  // Delete the initial src directory to replace it with our rule
  tree.delete('packages/conformance-rules/src/lib');
  tree.delete('packages/conformance-rules/src');

  await createRuleGenerator(tree, {
    name: 'example-conformance-rule',
    directory: 'packages/conformance-rules/src',
    category: 'consistency',
    description: 'An example conformance rule generated by the preset',
  });

  // Add the Nx Cloud specific targets
  const projectConfig = readProjectConfiguration(tree, 'conformance-rules');
  updateProjectConfiguration(tree, 'conformance-rules', {
    ...projectConfig,
    targets: {
      build: {
        executor: '@nx/conformance:bundle-rules',
        outputs: ['{options.outputPath}'],
        options: {
          outputPath: '{projectRoot}/dist',
        },
      },
      'publish-conformance-rules': {
        dependsOn: ['build'],
        command: 'npx nx-cloud publish-conformance-rules {projectRoot}/dist',
      },
    },
  });

  await formatFiles(tree);

  return runTasksInSerial(...tasks);
}
