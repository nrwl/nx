import { createRequire } from 'module';
import { valid } from 'semver';
import { readJsonFile } from './fileutils';
import { readMinReleaseAgePolicy } from './min-release-age/policy';
import { resolveCompliantVersion } from './min-release-age/resolve';
import {
  getWorkspaceRegistryUrlForDisplay,
  packageRegistryView,
} from './package-manager';
import { workspaceRoot } from './workspace-root';

/**
 * A build the publish workflow cuts from master rather than from a tag:
 * `23.3.0-pr.36841.f66e88b` from a pull request, `23.2.0-canary.20260908-89f02c1`
 * from the nightly. Each segment is matched with its leading digits so an
 * ordinary prerelease like `1.0.0-preview.1` does not qualify.
 */
function isPublishedFromMaster(version: string): boolean {
  return /-pr\.\d+\./.test(version) || /-canary\.\d/.test(version);
}

/**
 * Resolves `spec` to the version the workspace's package manager would
 * install under its minimum-release-age policy, verifies that version's
 * provenance, and returns it. Install the returned version, not `spec`.
 */
export async function resolveVersionWithProvenance(
  packageName: string,
  spec: string,
  root: string = workspaceRoot
): Promise<string> {
  let version = spec;
  if (!valid(spec)) {
    const policy = await readMinReleaseAgePolicy(root);
    if (policy.outcome === 'active') {
      version = (
        await resolveCompliantVersion(packageName, spec, policy.policy)
      ).version;
    }
  }
  return ensurePackageHasProvenance(packageName, version);
}

/**
 * Verifies that the given npm package has provenance attestations
 * generated by the GitHub Actions workflow at .github/workflows/publish.yml
 * in the nrwl/nx repository, and resolves to the exact version it verified.
 *
 * Will throw if the package does not have valid provenance.
 */
export async function ensurePackageHasProvenance(
  packageName: string,
  packageVersion: string
): Promise<string> {
  // this is used for locally released versions without provenance
  // do not set this for other reasons or you might be exposed to security risks
  if (process.env.NX_SKIP_PROVENANCE_CHECK === 'true') {
    return packageVersion;
  }

  try {
    const result = await packageRegistryView(packageName, packageVersion, [
      '--json',
      '--silent',
    ]);
    const parsed = JSON.parse(result);
    // `npm view <pkg>@<spec> --json` returns a bare object on npm <= 11 and
    // pnpm but an array on npm 12, even for a single resolved version. A version
    // range matches several versions and the registry lists all of them
    // (including deprecated ones the installer skips), so we cannot tell which
    // one will actually be installed; refuse rather than verify the wrong
    // artifact.
    if (Array.isArray(parsed) && parsed.length > 1) {
      throw new ProvenanceError(
        packageName,
        packageVersion,
        'Provenance can only be verified for a single version, but this version resolved to multiple candidates. Specify an exact version.'
      );
    }
    const npmViewResult = Array.isArray(parsed) ? parsed[0] : parsed;

    const attURL = npmViewResult?.dist?.attestations?.url;

    if (!attURL)
      throw new ProvenanceError(
        packageName,
        packageVersion,
        'No attestation URL found'
      );

    const verifiedVersion: string = npmViewResult.version;
    const requestedVersion = valid(packageVersion);
    if (
      !valid(verifiedVersion) ||
      (requestedVersion && verifiedVersion !== requestedVersion)
    ) {
      throw new ProvenanceError(
        packageName,
        packageVersion,
        `Requested version ${packageVersion} but the registry returned ${verifiedVersion}`
      );
    }

    const response = await fetch(attURL);

    if (!response.ok) {
      throw new ProvenanceError(
        packageName,
        packageVersion,
        `HTTP ${response.status}: ${response.statusText}`
      );
    }

    const attestations = (await response.json()) as {
      attestations: Attestation[];
    };

    const provenanceAttestation = attestations?.attestations?.find(
      (a) => a.predicateType === 'https://slsa.dev/provenance/v1'
    );

    const dsseEnvelopePayload = JSON.parse(
      Buffer.from(
        provenanceAttestation.bundle.dsseEnvelope.payload,
        'base64'
      ).toString()
    );

    const workflowParameters =
      dsseEnvelopePayload?.predicate?.buildDefinition?.externalParameters
        ?.workflow;

    // verify that provenance was actually generated from the right publishing workflow
    if (!workflowParameters) {
      throw new ProvenanceError(
        packageName,
        packageVersion,
        'Missing workflow parameters in attestation'
      );
    }

    if (workflowParameters.repository !== 'https://github.com/nrwl/nx') {
      throw new ProvenanceError(
        packageName,
        packageVersion,
        'Repository does not match nrwl/nx'
      );
    }
    if (workflowParameters.path !== '.github/workflows/publish.yml') {
      throw new ProvenanceError(
        packageName,
        packageVersion,
        'Publishing workflow does not match .github/workflows/publish.yml'
      );
    }
    // PR and canary releases are published by this same workflow running on
    // master, so a tag for them does not exist and never will. Repository,
    // workflow path and the artifact digest are still checked, so this only
    // widens which ref of nrwl/nx is allowed to have built it.
    // Some older releases were tagged `v<version>`.
    const tagRefs = [
      `refs/tags/${verifiedVersion}`,
      `refs/tags/v${verifiedVersion}`,
    ];
    const allowedRefs = isPublishedFromMaster(verifiedVersion)
      ? [...tagRefs, 'refs/heads/master']
      : tagRefs;
    if (!allowedRefs.includes(workflowParameters.ref)) {
      throw new ProvenanceError(
        packageName,
        packageVersion,
        `Version ref does not match ${allowedRefs.join(' or ')}`
      );
    }

    // verify that provenance was generated from the exact same artifact as the one we are installing
    const distSha = Buffer.from(
      npmViewResult.dist.integrity.replace('sha512-', ''),
      'base64'
    ).toString('hex');
    const attestationSha = dsseEnvelopePayload.subject[0].digest.sha512;
    if (distSha !== attestationSha) {
      throw new ProvenanceError(
        packageName,
        packageVersion,
        'Integrity hash does not match attestation hash'
      );
    }
    return verifiedVersion;
  } catch (error) {
    if (error instanceof ProvenanceError) {
      throw error;
    }
    throw new ProvenanceError(
      packageName,
      packageVersion,
      error.message || error
    );
  }
}

export class ProvenanceError extends Error {
  constructor(packageName: string, packageVersion: string, error?: string) {
    let customRegistry: string | undefined = undefined;
    try {
      const registry = getWorkspaceRegistryUrlForDisplay(packageName);

      // Only consider it custom if it's not the default npm registry
      if (registry && !registry.includes('registry.npmjs.org')) {
        customRegistry = registry;
      }
    } catch {
      // If we can't determine the registry, proceed with default error message
    }
    const registryNote = customRegistry
      ? `This might be due to a custom registry configuration (${customRegistry}). Please check whether provenance is correctly configured for your registry.`
      : `This could indicate a security risk. Please double check https://www.npmjs.com/package/${packageName} to see if the package is published correctly or file an issue at https://github.com/nrwl/nx/issues.`;
    super(
      `An error occurred while checking the provenance of ${packageName}@${packageVersion}. ${registryNote} To disable this check at your own risk, you can set the NX_SKIP_PROVENANCE_CHECK environment variable to true. \n Error: ${
        error ?? ''
      }`
    );
  }
}

export function getNxPackageGroup(): string[] {
  const packageJsonPath = createRequire(__filename).resolve('nx/package.json');
  const packageJson = readJsonFile(packageJsonPath);

  if (!packageJson['nx-migrations']?.packageGroup) {
    return ['nx'];
  }

  const packages = packageJson['nx-migrations'].packageGroup.filter(
    (dep: any) => typeof dep === 'string' && dep.startsWith('@nx/')
  );
  packages.push('nx');
  return packages;
}

type Attestation = {
  predicateType: string;
  bundle: {
    dsseEnvelope: {
      payload: string; // base64 encoded JSON
      payloadType: string;
      signatures: {
        keyid: string;
        sig: string;
      }[];
    };
    mediaType: string;
    [x: string]: unknown;
  };
  [x: string]: unknown;
};

// referh to https://slsa.dev/spec/v1.1/provenance#schema
export type DecodedAttestationPayload = {
  _type: 'https://in-toto.io/Statement/v1';
  subject: unknown[];
  predicateType: 'https://slsa.dev/provenance/v1';
  predicate: {
    buildDefinition: {
      buildType: string;
      externalParameters: Record<string, any>;
      internalParameters?: Record<string, any>;
      resolvedDependencies?: ResourceDescriptor[];
    };
    runDetails: {
      builder: {
        id: string;
        builderDependencies?: ResourceDescriptor[];
        version?: Record<string, string>;
      };
      metadata?: {
        invocationId?: string;
        startedOn?: string; // <YYYY>-<MM>-<DD>T<hh>:<mm>:<ss>Z
        finishedOn?: string; // <YYYY>-<MM>-<DD>T<hh>:<mm>:<ss>Z
      };
      byproducts?: ResourceDescriptor[];
    };
  };
};

export interface ResourceDescriptor {
  uri?: string;
  digest?: {
    sha256?: string;
    sha512?: string;
    gitCommit?: string;
    [key: string]: string | undefined;
  };
  name?: string;
  downloadLocation?: string;
  mediaType?: string;
  content?: string;
  annotations?: {
    [key: string]: any;
  };
}
