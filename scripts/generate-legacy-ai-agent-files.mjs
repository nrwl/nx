// Regenerates legacy-agent-files.ts: every file older `nx configure-ai-agents`
// versions copied from nrwl/nx-ai-agents-config's `generated/` folder.
// Usage: node scripts/generate-legacy-ai-agent-files.mjs <full-clone-of-that-repo>

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

// Must match fingerprintAgentFile in packages/nx/src/ai/set-up-ai-agents/legacy-agent-config.ts.
function fingerprintAgentFile(content) {
  return createHash('sha256')
    .update(content.toLowerCase().replace(/[^a-z0-9]/g, ''))
    .digest('hex')
    .slice(0, 16);
}

const repoPath = process.argv[2];
if (!repoPath) {
  console.error(
    'Usage: node scripts/generate-legacy-ai-agent-files.mjs <path-to-nx-ai-agents-config-clone>'
  );
  process.exit(1);
}

// Only these generated folders were ever copied into workspaces. `.codex/config.toml`
// was merged into the workspace config rather than copied, so it is excluded.
const copiedFolders = [
  '.agents',
  '.cursor',
  '.opencode',
  '.codex',
  '.github',
  '.gemini',
];
const excludedPaths = new Set(['.codex/config.toml']);

function git(...args) {
  return execFileSync('git', ['-C', repoPath, ...args], {
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
  });
}

const commits = git('rev-list', 'HEAD').trim().split('\n');
const blobsByPath = new Map();

for (const commit of commits) {
  const tree = git('ls-tree', '-r', commit, '--', 'generated/');
  for (const line of tree.split('\n')) {
    if (!line) continue;
    const [meta, path] = line.split('\t');
    const [, type, blob] = meta.split(' ');
    if (type !== 'blob') continue;
    const workspacePath = path.slice('generated/'.length);
    const folder = copiedFolders.find((f) => workspacePath.startsWith(`${f}/`));
    if (!folder || excludedPaths.has(workspacePath)) continue;
    if (!blobsByPath.has(workspacePath))
      blobsByPath.set(workspacePath, new Set());
    blobsByPath.get(workspacePath).add(blob);
  }
}

const fingerprintByBlob = new Map();
const entries = [...blobsByPath.keys()].sort().map((path) => {
  const fingerprints = new Set();
  for (const blob of blobsByPath.get(path)) {
    if (!fingerprintByBlob.has(blob)) {
      fingerprintByBlob.set(
        blob,
        fingerprintAgentFile(git('cat-file', 'blob', blob))
      );
    }
    fingerprints.add(fingerprintByBlob.get(blob));
  }
  return [path, [...fingerprints].sort()];
});

const outputPath = join(
  fileURLToPath(new URL('.', import.meta.url)),
  '..',
  'packages/nx/src/ai/set-up-ai-agents/legacy-agent-files.ts'
);

const body = entries
  .map(
    ([path, fingerprints]) =>
      `  ${JSON.stringify(path)}: [\n${fingerprints
        .map((f) => `    ${JSON.stringify(f)},`)
        .join('\n')}\n  ],`
  )
  .join('\n');

writeFileSync(
  outputPath,
  `// Generated by scripts/generate-legacy-ai-agent-files.mjs. Do not edit by hand.
// Files older versions of \`nx configure-ai-agents\` copied into workspaces, with
// the fingerprints (see fingerprintAgentFile) of every shipped version.
export const legacyAgentFiles: Record<string, readonly string[]> = {
${body}
};
`
);

// Match the repository's formatting so regenerating produces a clean diff.
execFileSync('npx', ['oxfmt', outputPath], { stdio: 'inherit' });

console.log(
  `Wrote ${entries.length} paths (${fingerprintByBlob.size} file versions) to ${outputPath}`
);
